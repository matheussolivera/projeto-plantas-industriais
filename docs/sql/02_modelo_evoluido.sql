-- Modelo relacional evoluido (3FN), com integridade referencial, restricoes e indices
-- =============================================================================

CREATE TABLE unidades_federativas (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sigla   CHAR(2)     NOT NULL,
    nome    VARCHAR(60) NOT NULL,
    regiao  VARCHAR(20) NOT NULL,
    CONSTRAINT uk_uf_sigla UNIQUE (sigla)
);

CREATE TABLE usuarios (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL,
    nome_completo VARCHAR(100) NOT NULL,
    senha_hash    VARCHAR(120) NOT NULL,
    perfil        VARCHAR(20)  NOT NULL CHECK (perfil IN ('ADMIN', 'OPERADOR')),
    ativo         BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_usuario_username UNIQUE (username)
);

CREATE TABLE plantas_industriais (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_planta        VARCHAR(20)   NOT NULL,
    nome                 VARCHAR(120)  NOT NULL,
    cidade               VARCHAR(100)  NOT NULL,
    uf_id                BIGINT        NOT NULL,
    latitude             DECIMAL(9, 6) NOT NULL CHECK (latitude BETWEEN -90.0 AND 90.0),
    longitude            DECIMAL(9, 6) NOT NULL CHECK (longitude BETWEEN -180.0 AND 180.0),
    ano_inicio_operacao  INT           NOT NULL CHECK (ano_inicio_operacao BETWEEN 1900 AND 2030),
    area_m2              INT           NOT NULL CHECK (area_m2 > 0),
    funcionarios         INT           NOT NULL CHECK (funcionarios >= 0),
    nivel_automacao      VARCHAR(20)   NOT NULL CHECK (nivel_automacao IN ('BAIXO', 'MEDIO', 'ALTO', 'MUITO_ALTO')),
    linhas_automatizadas INT           NOT NULL CHECK (linhas_automatizadas >= 0),
    certificacao_iso9001 BOOLEAN       NOT NULL,
    status               VARCHAR(20)   NOT NULL CHECK (status IN ('EM_IMPLANTACAO', 'ATIVA', 'EM_MANUTENCAO', 'SUSPENSA', 'DESATIVADA')),
    criado_em            TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em        TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_planta_codigo UNIQUE (codigo_planta),
    CONSTRAINT uk_planta_nome UNIQUE (nome),
    CONSTRAINT fk_planta_uf FOREIGN KEY (uf_id) REFERENCES unidades_federativas (id)
);

CREATE INDEX idx_planta_uf ON plantas_industriais (uf_id);
CREATE INDEX idx_planta_status ON plantas_industriais (status);
CREATE INDEX idx_planta_nivel_automacao ON plantas_industriais (nivel_automacao);

CREATE TABLE linhas_producao (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    planta_id       BIGINT       NOT NULL,
    codigo_linha    VARCHAR(30)  NOT NULL,
    nome            VARCHAR(100) NOT NULL,
    tipo_automacao  VARCHAR(60)  NOT NULL,
    capacidade_hora INT          NOT NULL CHECK (capacidade_hora > 0),
    ativa           BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_linha_planta_codigo UNIQUE (planta_id, codigo_linha),
    CONSTRAINT fk_linha_planta FOREIGN KEY (planta_id) REFERENCES plantas_industriais (id) ON DELETE CASCADE
);

CREATE INDEX idx_linha_planta ON linhas_producao (planta_id);

CREATE TABLE historico_status_planta (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    planta_id       BIGINT       NOT NULL,
    status_anterior VARCHAR(20),
    status_novo     VARCHAR(20)  NOT NULL,
    justificativa   VARCHAR(300) NOT NULL,
    alterado_por    VARCHAR(80)  NOT NULL,
    alterado_em     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_historico_planta FOREIGN KEY (planta_id) REFERENCES plantas_industriais (id) ON DELETE CASCADE
);

CREATE INDEX idx_historico_planta ON historico_status_planta (planta_id);
CREATE INDEX idx_historico_data ON historico_status_planta (alterado_em);
